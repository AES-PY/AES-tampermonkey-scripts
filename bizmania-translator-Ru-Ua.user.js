    function getTranslation(text) {
        if (!text) {
            return null;
        }
        const normalizedText = text
            .replace(/\u00A0/g, " ")
            .replace(/\s+/g, " ")
            .trim();
        if (!normalizedText) {
            return null;
        }
        const promoRegex =
            /^С\s+(\d{2}\.\d{2}\.\d{4})\s+по\s+(\d{2}\.\d{2}\.\d{4})\s+скидка\s+(\d+(?:\s*%)?)\s+на стоимость повышения уровня отдела$/i;
        const promoMatch = normalizedText.match(promoRegex);
        if (promoMatch) {
            const date1 = promoMatch[1];
            const date2 = promoMatch[2];
            const percent = promoMatch[3];
            if (currentLang === "uk") {
                return `З ${date1} по ${date2} ` + `знижка ${percent} ` + `на вартість підвищення рівня відділу`;
            }
            if (currentLang === "en") {
                return (
                    `From ${date1} to ${date2} ` +
                    `discount ${percent} ` +
                    `on the cost of upgrading the department level`
                );
            }
        }
        if (dictionary[normalizedText] && dictionary[normalizedText][currentLang]) {
            return dictionary[normalizedText][currentLang];
        }
        const doubleNumberRegex = /(\d+(?:[\s.,]\d+)*)\s*\/\s*(\d+(?:[\s.,]\d+)*)/;
        const doubleMatch = normalizedText.match(doubleNumberRegex);
        if (doubleMatch) {
            const fullFraction = doubleMatch[0];
            const n1 = doubleMatch[1];
            const n2 = doubleMatch[2];
            const templateText = normalizedText.replace(fullFraction, "{n1} / {n2}");
            if (dictionary[templateText] && dictionary[templateText][currentLang]) {
                return dictionary[templateText][currentLang].replace("{n1}", n1).replace("{n2}", n2);
            }
        }
        const percentRegex = /\d+\s*%/;
        const percentMatch = normalizedText.match(percentRegex);
        if (percentMatch) {
            const percentPart = percentMatch[0];
            const templateText = normalizedText.replace(percentPart, "{percent}");
            if (dictionary[templateText] && dictionary[templateText][currentLang]) {
                return dictionary[templateText][currentLang].replace("{percent}", percentPart);
            }
        }
        const millionsPairRegex =
    /(\d+(?:[\s.,]\d+)*)\s*млн\.\s*\|\s*(\d+(?:[\s.,]\d+)*)\s*млн\./;

        const millionsPairMatch = normalizedText.match(millionsPairRegex);

        if (millionsPairMatch) {
            const n1 = millionsPairMatch[1];
            const n2 = millionsPairMatch[2];

            const templateText = normalizedText.replace(
                millionsPairMatch[0],
                "{n1} млн. | {n2} млн."
            );

            if (dictionary[templateText] && dictionary[templateText][currentLang]) {
                return dictionary[templateText][currentLang]
                    .replace("{n1}", n1)
                    .replace("{n2}", n2);
            }
        }
        const levelDateRegex =
    /^Уровень получен:\s*(\d{2}\.\d{2}\.\d{4})$/i;

const levelDateMatch = normalizedText.match(levelDateRegex);

if (levelDateMatch) {
    const date = levelDateMatch[1];
    const templateText = "Уровень получен: {date}";

    if (dictionary[templateText] && dictionary[templateText][currentLang]) {
        return dictionary[templateText][currentLang]
            .replace("{date}", date);
    }
}

        const numberRegex = /\d+(?:[\s.,]\d+)*/;
        const numMatch = normalizedText.match(numberRegex);
        if (numMatch && !normalizedText.includes("%") && !normalizedText.includes("/")) {
            const numberPart = numMatch[0];
            const templateText = normalizedText.replace(numberPart, "{n}");
            if (dictionary[templateText] && dictionary[templateText][currentLang]) {
                return dictionary[templateText][currentLang].replace("{n}", numberPart);
            }
        }
        if (normalizedText.startsWith("Компания ")) {
            const namePart = normalizedText.substring("Компания ".length).trim();
            if (namePart) {
                const templateText = "Компания {name}";
                if (dictionary[templateText] && dictionary[templateText][currentLang]) {
                    return dictionary[templateText][currentLang].replace("{name}", namePart);
                }
            }

        }
        if (normalizedText.startsWith("Город ")) {
            const namePart = normalizedText.substring("Город ".length).trim();

            if (namePart) {
                const city = cityTranslations[namePart];
                const translatedName = city?.[currentLang] || namePart;

                if (currentLang === "uk") {
                    return `Місто ${translatedName}`;
                }

                if (currentLang === "en") {
                    return `City ${translatedName}`;
        }
    }
}
                if (normalizedText.startsWith("Личный кабинет:")) {
            const namePart = normalizedText.substring("Личный кабинет:".length).trim();

            if (namePart) {
                const city = cityTranslations[namePart];
                const translatedName = city?.[currentLang] || namePart;

                if (currentLang === "uk") {
                    return `Особистий кабінет: ${translatedName}`;
                }

                if (currentLang === "en") {
                    return `Personal Account: ${translatedName}`;
        }
    }
}


        return null;
    }
