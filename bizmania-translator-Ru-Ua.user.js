    const connectedFrames = new WeakSet();
    function connectPopupIframe() {
        if (!isTopWindow) {
            return;
        }
        const topDocument = window.top.document;
        const iframe = topDocument.getElementById("popupContent");
        if (!iframe) {
            return;
        }
        if (connectedFrames.has(iframe)) {
            try {
                if (iframe.contentDocument && iframe.contentDocument.body) {
                    translateElement(iframe.contentDocument.body);
                    translateComplexBlocks(iframe.contentDocument);
                    observeDocument(iframe.contentDocument);
                }
            } catch (error) {}
            return;
        }
        connectedFrames.add(iframe);
        iframe.addEventListener("load", () => {
            try {
                const frameDocument = iframe.contentDocument;
                if (!frameDocument) {
                    return;
                }
                if (frameDocument.body) {
                    translateElement(frameDocument.body);
                    translateComplexBlocks(frameDocument);
                    observeDocument(frameDocument);
                }
            } catch (error) {
                console.warn("[Bizmania Translator] " + "Не удалось обработать popup iframe:", error);
            }
        });
        try {
            if (iframe.contentDocument && iframe.contentDocument.body) {
                translateElement(iframe.contentDocument.body);
                translateComplexBlocks(iframe.contentDocument);
                observeDocument(iframe.contentDocument);
            }
        } catch (error) {}
    }
    function startPopupWatcher() {
        if (!isTopWindow || !document.body) {
            return;
        }
        connectPopupIframe();
        let attempts = 0;
        const timer = setInterval(() => {
            connectPopupIframe();
            attempts++;
            if (attempts >= 120) {
                clearInterval(timer);
            }
        }, 500);
    }
    function initTranslation() {
        if (!document.body) {
            return;
        }
        if (currentLang !== "ru") {
            translateComplexBlocks(document);
            translateElement(document.body);
        }
        observeDocument(document);
        if (isTopWindow) {
            createLanguageSwitcher();
            startPopupWatcher();
        }
    }
    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", initTranslation, { once: !0 });
    } else {
        initTranslation();
    }
