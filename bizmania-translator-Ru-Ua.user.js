  // Объединяем все блоки в один индекс. Внутри нет точных дублей.
  const DICTIONARY = Object.assign({}, UI, PRODUCTS, SERVICES, SPECIAL, DAYS_OF_WEEK);

  const LANGUAGE_STORAGE_KEY = 'bizmania-translator-language';
  const DEFAULT_LANGUAGE = 'ua';
  let currentLanguage = localStorage.getItem(LANGUAGE_STORAGE_KEY) || DEFAULT_LANGUAGE;
  if (!['ru', 'ua', 'en'].includes(currentLanguage)) currentLanguage = DEFAULT_LANGUAGE;

  // Более длинные фразы обрабатываются раньше коротких.
  // Границы построены по Unicode-буквам/цифрам, а не по регистру.
  // Само сравнение регистрозависимое: флаг i НЕ используется.
  const translations = Object.entries(DICTIONARY)
    .sort((a, b) => b[0].length - a[0].length)
    .map(([ru, data]) => {
      const escaped = ru.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      return {
        ru,
        data,
        regex: new RegExp(`(?<![\p{L}\p{N}_])${escaped}(?![\p{L}\p{N}_])`, 'gu')
      };
    });

  const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'CODE', 'PRE']);
  const ATTRIBUTES = ['title', 'placeholder', 'aria-label', 'alt'];
  const VALUE_INPUT_TYPES = new Set(['button', 'submit', 'reset']);
  const originalText = new WeakMap();
  const originalAttributes = new WeakMap();
  const originalValues = new WeakMap();
  const trackedDocuments = new Set();
  const documentObservers = new WeakMap();

  function getTranslation(source) {
    if (currentLanguage === 'ru') return source;
    let result = source;
    for (const item of translations) {
      item.regex.lastIndex = 0;
      const replacement = item.data[currentLanguage];
      result = result.replace(item.regex, replacement);
    }
    return result;
  }

  function isProtectedElement(element) {
    return !!(element && element.nodeType === Node.ELEMENT_NODE &&
      (element.id === 'bm-language-switcher-host' ||
       element.closest?.('#bm-language-switcher-host')));
  }

  function isSkippedElement(element) {
    return !element || element.nodeType !== Node.ELEMENT_NODE || SKIP_TAGS.has(element.tagName) || isProtectedElement(element);
  }

  function updateTextNode(node) {
    if (!node || node.nodeType !== Node.TEXT_NODE) return;
    const parent = node.parentElement;
    if (!parent || SKIP_TAGS.has(parent.tagName) || isProtectedElement(parent)) return;

    const current = node.nodeValue || '';
    let source = originalText.get(node);
    if (source === undefined) {
      source = current;
      originalText.set(node, source);
    } else {
      const expected = getTranslation(source);
      // Если сайт заменил содержимое динамически, принимаем новое значение как оригинал.
      if (current !== expected && current !== source) {
        source = current;
        originalText.set(node, source);
      }
    }

    const translated = getTranslation(source);
    if (current !== translated) node.nodeValue = translated;
  }

  function updateAttribute(element, attr) {
    if (!element || isSkippedElement(element) || !element.hasAttribute(attr)) return;
    let map = originalAttributes.get(element);
    if (!map) {
      map = new Map();
      originalAttributes.set(element, map);
    }
    const current = element.getAttribute(attr) || '';
    let source = map.get(attr);
    if (source === undefined) {
      source = current;
      map.set(attr, source);
    } else {
      const expected = getTranslation(source);
      if (current !== expected && current !== source) {
        source = current;
        map.set(attr, source);
      }
    }
    const translated = getTranslation(source);
    if (current !== translated) element.setAttribute(attr, translated);
  }

  function updateInputValue(element) {
    if (!element || isSkippedElement(element) || element.tagName !== 'INPUT') return;
    if (!VALUE_INPUT_TYPES.has((element.type || '').toLowerCase())) return;
    let source = originalValues.get(element);
    const current = element.value || '';
    if (source === undefined) {
      source = current;
      originalValues.set(element, source);
    } else {
      const expected = getTranslation(source);
      if (current !== expected && current !== source) {
        source = current;
        originalValues.set(element, source);
      }
    }
    const translated = getTranslation(source);
    if (current !== translated) element.value = translated;
  }

  function translateElement(element) {
    if (!element) return;
    if (element.nodeType === Node.TEXT_NODE) {
      updateTextNode(element);
      return;
    }
    if (isSkippedElement(element)) return;

    for (const attr of ATTRIBUTES) updateAttribute(element, attr);
    updateInputValue(element);

    for (const child of element.childNodes) translateElement(child);
  }

  function refreshDocument(doc) {
    if (!doc || !doc.body) return;
    translateElement(doc.body);
  }

  function revealPage() {
    document.documentElement?.removeAttribute(EARLY_HIDE_ATTRIBUTE);
    document.getElementById(EARLY_HIDE_STYLE_ID)?.remove();
  }

  function attachFrame(frame) {
    if (!frame || frame.nodeType !== Node.ELEMENT_NODE) return;
    const processFrame = () => {
      try {
        const doc = frame.contentDocument;
        if (doc) processDocument(doc);
      } catch (_) {
        // Кросс-доменные iframe пропускаются.
      }
    };
    processFrame();
    frame.addEventListener('load', processFrame);
  }

  function processDocument(doc) {
    if (!doc || !doc.body || trackedDocuments.has(doc)) return;
    trackedDocuments.add(doc);
    refreshDocument(doc);

    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === 'characterData') {
          updateTextNode(mutation.target);
          continue;
        }

        for (const node of mutation.addedNodes) {
          if (node.nodeType === Node.TEXT_NODE) {
            updateTextNode(node);
            continue;
          }
          if (node.nodeType !== Node.ELEMENT_NODE || isProtectedElement(node)) continue;
          translateElement(node);
          node.querySelectorAll?.('iframe, frame').forEach(attachFrame);
        }
      }
    });

    observer.observe(doc.documentElement, {
      subtree: true,
      childList: true,
      characterData: true
    });
    documentObservers.set(doc, observer);
    doc.querySelectorAll('iframe, frame').forEach(attachFrame);
  }

  function refreshAllDocuments() {
    for (const doc of trackedDocuments) refreshDocument(doc);
  }

  function updateSwitcherUI() {
    const host = document.getElementById('bm-language-switcher-host');
    const switcher = host?.shadowRoot?.querySelector('.switcher');
    if (!switcher) return;

    switcher.querySelectorAll('button[data-lang]').forEach((button) => {
      const active = button.dataset.lang === currentLanguage;
      button.classList.toggle('active', active);
      button.setAttribute('aria-pressed', String(active));
    });
  }

  function setLanguage(language) {
    if (!['ru', 'ua', 'en'].includes(language)) return;
    currentLanguage = language;
    localStorage.setItem(LANGUAGE_STORAGE_KEY, currentLanguage);
    document.documentElement.lang = currentLanguage === 'ua' ? 'uk' : currentLanguage;
    refreshAllDocuments();
    updateSwitcherUI();
  }

