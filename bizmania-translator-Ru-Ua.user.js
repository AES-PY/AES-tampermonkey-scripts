    function translateDateParts(text) {
        if (currentLang === "ru" || !text) {
            return text;
        }
        let result = text;
        for (const [source, translations] of Object.entries(dateTranslations)) {
            const translated = translations[currentLang];
            if (!translated) {
                continue;
            }
            result = result.replace(
                new RegExp("(^|[^А-Яа-яЁёЇїІіЄєҐґA-Za-z])" + source + "(?=$|[^А-Яа-яЁёЇїІіЄєҐґA-Za-z])", "g"),
                "$1" + translated
            );
        }
        return result;
    }
    function translateTimeParts(text) {
        if (currentLang === "ru" || !text) {
            return text;
        }
        let result = text;
        for (const [source, translations] of Object.entries(timeTranslations)) {
            const translated = translations[currentLang];
            if (!translated) {
                continue;
            }
            result = result.split(source).join(translated);
        }
        return result;
    }
    function translateElement(node) {
        if (currentLang === "ru" || !node) {
            return;
        }
        if (node.nodeType === Node.TEXT_NODE) {
            const originalText = node.nodeValue;
            if (!originalText || !originalText.trim()) {
                return;
            }
            const trimmedText = originalText.trim();
            const translated = getTranslation(trimmedText);
            if (translated) {
                const leading = originalText.match(/^\s*/)?.[0] || "";
                const trailing = originalText.match(/\s*$/)?.[0] || "";
                const newValue = leading + translated + trailing;
                if (node.nodeValue !== newValue) {
                    node.nodeValue = newValue;
                }
                return;
            }
            const dateTranslated = translateDateParts(originalText);
            if (dateTranslated !== originalText) {
                node.nodeValue = dateTranslated;
                return;
            }
            const timeTranslated = translateTimeParts(originalText);
            if (timeTranslated !== originalText) {
                node.nodeValue = timeTranslated;
            }
            return;
        }
        if (node.nodeType !== Node.ELEMENT_NODE) {
            return;
        }
        if (node.id === "bizmania-lang-switcher") {
            return;
        }
        if (node.closest && node.closest("#bizmania-lang-switcher")) {
            return;
        }
        if (node.hasAttribute("value")) {
            const value = node.getAttribute("value");
            if (value) {
                const translated = getTranslation(value.trim());
                if (translated) {
                    if (node.getAttribute("value") !== translated) {
                        node.setAttribute("value", translated);
                    }
                    if ("value" in node && node.value !== translated) {
                        node.value = translated;
                    }
                }
            }
        }
        if (node.hasAttribute("placeholder")) {
            const placeholder = node.getAttribute("placeholder");
            if (placeholder) {
                const translated = getTranslation(placeholder.trim());
                if (translated) {
                    node.setAttribute("placeholder", translated);
                }
            }
        }
        if (node.hasAttribute("title")) {
            const title = node.getAttribute("title");
            if (title) {
                const translated = getTranslation(title.trim());
                if (translated) {
                    node.setAttribute("title", translated);
                }
            }
        }
        if (node.hasAttribute("alt")) {
            const alt = node.getAttribute("alt");
            if (alt) {
                const translated = getTranslation(alt.trim());
                if (translated) {
                    node.setAttribute("alt", translated);
                }
            }
        }
        if (node.hasAttribute("aria-label")) {
            const ariaLabel = node.getAttribute("aria-label");
            if (ariaLabel) {
                const translated = getTranslation(ariaLabel.trim());
                if (translated) {
                    node.setAttribute("aria-label", translated);
                }
            }
        }
        for (const child of node.childNodes) {
            translateElement(child);
        }
    }
    function translateProgressCells(targetDocument = document) {
        if (currentLang === "ru" || !targetDocument) {
            return;
        }
        const cells = targetDocument.querySelectorAll("td");
        cells.forEach((labelCell) => {
            const labelText = labelCell.textContent
                .replace(/\u00A0/g, " ")
                .replace(/\s+/g, " ")
                .trim();
            if (labelText !== "Прогресс:") {
                return;
            }
            const valueCell = labelCell.nextElementSibling;
            if (!valueCell) {
                return;
            }
            const valueText = valueCell.textContent
                .replace(/\u00A0/g, " ")
                .replace(/\s+/g, " ")
                .trim();
            const progressMatch = valueText.match(/^(\d+(?:[\s.,]\d+)*)\s*\/\s*(\d+(?:[\s.,]\d+)*)$/);
            if (!progressMatch) {
                return;
            }
            const translatedLabel =
                currentLang === "uk" ? "Прогрес:" : currentLang === "en" ? "Progress:" : "Прогресс:";
            if (labelCell.textContent !== translatedLabel) {
                labelCell.textContent = translatedLabel;
            }
        });
    }
    function translateComplexBlocks(targetDocument = document) {
        if (currentLang === "ru" || !targetDocument) {
            return;
        }
        const promoElements = targetDocument.querySelectorAll("p.text b");
        promoElements.forEach((element) => {
            const text = element.textContent
                .replace(/\u00A0/g, " ")
                .replace(/\s+/g, " ")
                .trim();
            const translated = getTranslation(text);
            if (translated && element.textContent !== translated) {
                element.textContent = translated;
            }
        });
        translateProgressCells(targetDocument);
    }
    const observers = new WeakMap();
    function observeDocument(targetDocument) {
        if (!targetDocument || !targetDocument.body) {
            return;
        }
        if (observers.has(targetDocument)) {
            return;
        }
        const observer = new MutationObserver((mutations) => {
            for (const mutation of mutations) {
                if (mutation.type === "childList") {
                    for (const addedNode of mutation.addedNodes) {
                        if (addedNode.nodeType === Node.ELEMENT_NODE) {
                            translateElement(addedNode);
                        } else if (addedNode.nodeType === Node.TEXT_NODE) {
                            translateElement(addedNode);
                        }
                    }
                }
                if (mutation.type === "characterData") {
                    translateElement(mutation.target);
                }
                if (mutation.type === "attributes") {
                    translateElement(mutation.target);
                }
            }
            translateComplexBlocks(targetDocument);
            if (targetDocument === document && isTopWindow) {
                connectPopupIframe();
            }
        });
        observer.observe(targetDocument.body, {
            childList: !0,
            subtree: !0,
            characterData: !0,
            attributes: !0,
            attributeFilter: ["title", "alt", "placeholder", "value", "aria-label"],
        });
        observers.set(targetDocument, observer);
    }
