  const DICTIONARY = Object.assign({}, UI, PRODUCTS, SERVICES, SPECIAL, DAYS_OF_WEEK);

  // Более длинные фразы обрабатываются раньше коротких.
  // Сравнение регистрозависимое; знаки препинания и пробелы являются частью ключа.
  const translations = Object.entries(DICTIONARY)
    .sort((a, b) => b[0].length - a[0].length)
    .map(([ru, ua]) => {
      const escaped = ru.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&');
      return [
        new RegExp(`(?<![А-Яа-яЁё])${escaped}(?![А-Яа-яЁё])`, 'g'),
        ua
      ];
    });

  const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'CODE', 'PRE']);
  const ATTRIBUTES = ['title', 'placeholder', 'aria-label', 'alt'];
  const processedDocs = new WeakSet();

  function translateText(text) {
    let result = text;
    for (const [regex, ua] of translations) {
      result = result.replace(regex, ua);
    }
    return result;
  }

  function isSkippedElement(element) {
    return !element || element.nodeType !== Node.ELEMENT_NODE ||
      SKIP_TAGS.has(element.tagName);
  }

  function translateElement(element) {
    if (!element) return;

    if (element.nodeType === Node.TEXT_NODE) {
      const parent = element.parentElement;
      if (!parent || SKIP_TAGS.has(parent.tagName)) return;

      const oldText = element.nodeValue;
      const newText = translateText(oldText);
      if (oldText !== newText) {
        element.nodeValue = newText;
      }
      return;
    }

    if (isSkippedElement(element)) return;

    for (const attr of ATTRIBUTES) {
      if (!element.hasAttribute(attr)) continue;

      const oldValue = element.getAttribute(attr);
      const newValue = translateText(oldValue);
      if (oldValue !== newValue) {
        element.setAttribute(attr, newValue);
      }
    }

    if (
      element.tagName === 'INPUT' &&
      (element.type === 'button' || element.type === 'submit')
    ) {
      const oldValue = element.value;
      const newValue = translateText(oldValue);
      if (oldValue !== newValue) {
        element.value = newValue;
      }
    }

    for (const child of element.childNodes) {
      translateElement(child);
    }
  }

  function attachFrame(frame) {
    try {
      if (frame.contentDocument) {
        processDocument(frame.contentDocument);
      }
    } catch (e) {
      // Кросс-доменные frame/iframe пропускаются.
    }

    frame.addEventListener('load', () => {
      try {
        processDocument(frame.contentDocument);
      } catch (e) {
        // Кросс-доменные frame/iframe пропускаются.
      }
    });
  }

  function processDocument(doc) {
    if (!doc || !doc.body || processedDocs.has(doc)) return;

    processedDocs.add(doc);
    translateElement(doc.body);

    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === 'characterData') {
          translateElement(mutation.target);
          continue;
        }

        for (const node of mutation.addedNodes) {
          try {
            if (node.nodeType === Node.TEXT_NODE) {
              translateElement(node);
            } else if (node.nodeType === Node.ELEMENT_NODE) {
              translateElement(node);

              if (node.tagName === 'IFRAME' || node.tagName === 'FRAME') {
                attachFrame(node);
              }

              node.querySelectorAll?.('iframe, frame').forEach(attachFrame);
            }
          } catch (e) {
            // Ошибка одного динамического узла не останавливает перевод.
          }
        }
      }
    });

    observer.observe(doc.documentElement, {
      subtree: true,
      childList: true,
      characterData: true
    });

    doc.querySelectorAll('iframe, frame').forEach(attachFrame);
  }

  function startTranslator() {
    processDocument(document);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', startTranslator, { once: true });
  } else {
    startTranslator();
  }
